"""Build app/src/main/assets/oui/makers.tsv from Wireshark's `manuf` file.

Usage (the owner or an agent runs it; download the source at most once a week, as Wireshark asks):
    curl -L https://www.wireshark.org/download/automated/data/manuf -o manuf
    python tools/make_makers.py manuf

Output lines: <hex prefix>\t<maker>, where the prefix has 6, 7 or 9 hex digits for 24, 28 and
36-bit blocks. The maker is the full vendor name (third column) with common company suffixes
removed, so it reads well and the file stays small.

Source: Wireshark (https://www.wireshark.org), "manuf" generated by `tshark -G manuf` from the
IEEE registration authority's public listings. Wireshark: "Most parts of Wireshark are covered
by a GPL version 2 or later license" (README.md). See CREDITS.md.
"""
import re
import sys
from datetime import date
from pathlib import Path

SUFFIX = re.compile(r"[,.]?\s+(inc|incorporated|corp|corporation|co|company|ltd|limited|llc|gmbh|ag|sa|s\.a|bv|b\.v|oy|ab|as|srl|s\.r\.l|spa|s\.p\.a|pte|pty|plc|kg|co\.,?\s*ltd)\.?$", re.I)


def tidy(name: str) -> str:
    n = name.strip()
    for _ in range(3):
        n2 = SUFFIX.sub("", n).strip().rstrip(",").strip()
        if n2 == n:
            break
        n = n2
    return n[:48]


def main() -> int:
    src = Path(sys.argv[1])
    out = Path(__file__).resolve().parents[1] / "app" / "src" / "main" / "assets" / "oui" / "makers.tsv"
    rows = []
    for line in src.read_text(encoding="utf-8", errors="replace").splitlines():
        if not line or line.startswith("#"):
            continue
        cols = line.split("\t")
        if len(cols) < 2:
            continue
        block = cols[0].strip()
        bits = 24
        if "/" in block:
            block, b = block.split("/", 1)
            bits = int(b)
        if bits not in (24, 28, 36):
            continue
        hexs = block.replace(":", "").replace("-", "").upper()[: bits // 4]
        name = tidy(cols[2] if len(cols) > 2 and cols[2].strip() else cols[1])
        if name:
            rows.append(f"{hexs}\t{name}")
    out.parent.mkdir(parents=True, exist_ok=True)
    header = (f"# Device makers by hardware-address prefix. Generated {date.today()} by tools/make_makers.py\n"
              "# from Wireshark's manuf file (https://www.wireshark.org/download/automated/data/manuf),\n"
              "# itself built from the IEEE registration authority listings. Credits: CREDITS.md.\n")
    out.write_text(header + "\n".join(rows) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(rows)} prefixes, {out.stat().st_size} bytes -> {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
